// npm run docs
// Regenerates, from the component code itself (so docs never drift):
//   styles/index.yaml                                   compact style + component index
//   skill/everyday-engineering/references/components.md the reference Claude.ai reads
import fs from "node:fs";
import path from "node:path";
import YAML from "yaml";
import { P, ok, readYaml, rel } from "./lib/core.mjs";
import { loadComponents } from "./lib/components.mjs";

const reg = await loadComponents();
const styles = readYaml(path.join(P.styles, "styles.yaml"));
const byStyle = {};
for (const c of Object.values(reg)) (byStyle[c.style] ??= []).push(c);

// ---- styles/index.yaml
const index = {
  note: "Generated by `npm run docs` from styles/styles.yaml and the component code. Do not edit by hand.",
  styles: styles.styles.map((s) => ({ ...s, components: (byStyle[s.folder] ?? []).map((c) => c.name) })),
  shared_components: (byStyle.shared ?? []).map((c) => c.name),
};
fs.writeFileSync(path.join(P.styles, "index.yaml"), YAML.stringify(index, { lineWidth: 0 }));

// ---- components.md
let md = `# Components reference\n\nGenerated by \`npm run docs\` from the component code. Each scene in scenes.yaml uses exactly one component.\n\n`;
md += `Common to every scene: \`id\` (S01, S02…), \`component\`, \`say\` (narration, speech-ready), optional \`chapter\` (YouTube chapter name), \`params\`.\n`;
md += `Timing: any \`cue\` / \`*_cue\` value is a short phrase copied **exactly** from that scene's \`say\`; the element appears when that phrase is spoken. Without a cue, items are spread evenly through the scene.\n`;
md += `Text fields accept \`$inline LaTeX$\`, \`**bold**\`, \`==yellow marker==\`, \`{red}red text{/red}\`. \`tex\` fields are LaTeX without dollar signs (escape backslashes in YAML double quotes: \`"\\\\frac{a}{b}"\`).\n`;
md += `Colors by brand name: navy, ink, red, blue, green, marker, muted, grid (or hex). Icons: Tabler outline names (tabler.io/icons).\n\n`;
const order = ["shared", ...styles.styles.map((s) => s.folder)];
for (const folder of order) {
  const list = byStyle[folder];
  if (!list?.length) continue;
  const s = styles.styles.find((x) => x.folder === folder);
  md += `## ${s ? `Style ${s.id} · ${s.name}` : "Shared (any style)"}\n\n`;
  for (const c of list) {
    md += `### \`${c.name}\`${c.navy ? " (navy background)" : ""}\n${c.describe}\n\n`;
    for (const [k, v] of Object.entries(c.params ?? {})) md += `- \`${k}\`${(c.required ?? []).includes(k) ? " **(required)**" : ""}: ${v}\n`;
    md += `\n`;
  }
}
const ref = path.join(P.root, "skill", "everyday-engineering", "references");
fs.mkdirSync(ref, { recursive: true });
fs.writeFileSync(path.join(ref, "components.md"), md);

// ---- styles.md (for style suggestions)
let sm = `# Styles\n\nGenerated by \`npm run docs\` from styles/styles.yaml. Suggest from A, B, C, D, F (E = Shorts, always produced).\n\n`;
for (const s of styles.styles) {
  sm += `## ${s.id} · ${s.name}\n${s.look}\n- Best for: ${(s.best_for ?? []).join("; ")}\n`;
  if (s.avoid_for) sm += `- Avoid for: ${s.avoid_for.join("; ")}\n`;
  if (s.needs) sm += `- Needs: ${s.needs}\n`;
  sm += `- Components: ${(byStyle[s.folder] ?? []).map((c) => "`" + c.name + "`").join(", ") || "(built automatically)"}\n\n`;
}
sm += `Shared components usable in any style: ${(byStyle.shared ?? []).map((c) => "`" + c.name + "`").join(", ")}.\n`;
fs.writeFileSync(path.join(ref, "styles.md"), sm);
ok(`Wrote ${rel(path.join(P.styles, "index.yaml"))}, ${rel(path.join(ref, "components.md"))} and styles.md`);
