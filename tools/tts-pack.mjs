// npm run tts-pack -- 001
// From scenes.yaml (the single source of truth) write:
//   script.md  — the readable narration with scene markers and estimated times
//   tts.md     — everything needed to record the voice in Gemini 3.8 Flash TTS
// Runs locally, so Claude never has to write the narration twice.
import fs from "node:fs";
import path from "node:path";
import { parseArgs, videoDir, ok, info, readYaml, rel, P } from "./lib/core.mjs";
import { loadVideo } from "./lib/video.mjs";
import { tokens } from "./lib/timing.mjs";
import { saveAndPush } from "./lib/git.mjs";

const args = parseArgs();
const dir = videoDir(args._[0]);
const v = loadVideo(dir);
const voice = readYaml(path.join(P.channel, "voice.yaml"));
const g = voice.gemini ?? {};
const maxWords = g.chunk_max_words ?? 280;
const wpm = 150;
const mmss = (s) => `${Math.floor(s / 60)}:${String(Math.round(s % 60)).padStart(2, "0")}`;

// ---- script.md
let t = 0;
let script = `# ${v.meta.title ?? v.name}\n\nGenerated from scenes.yaml by \`npm run tts-pack\`. Edit scenes.yaml, not this file.\n\n`;
let total = 0;
for (const s of v.scenes) {
  const n = tokens(s.say).length;
  script += `### ${s.id} · ${s.component} · ~${mmss(t)}\n\n${String(s.say ?? "").trim() || "_(no narration)_"}\n\n`;
  t += (n / wpm) * 60 + 0.5;
  total += n;
}
script += `---\n${total} words · about ${mmss(t)} at ${wpm} words per minute\n`;
fs.writeFileSync(path.join(dir, "script.md"), script);

// ---- chunks (split at scene boundaries)
const chunks = [];
let cur = null;
for (const s of v.scenes) {
  const say = String(s.say ?? "").trim();
  if (!say) continue;
  const n = tokens(say).length;
  if (!cur || (cur.words + n > maxWords && cur.words > 0)) {
    cur = { scenes: [], text: [], words: 0 };
    chunks.push(cur);
  }
  cur.scenes.push(s.id);
  cur.text.push(say);
  cur.words += n;
}
const pronounce = { ...(voice.pronounce ?? {}), ...(v.meta.pronounce ?? {}) };
const style = [g.style, v.meta.voice_note].filter(Boolean).join(" ");
let md = `# Voice recording package — ${v.meta.title ?? v.name}

Generated by \`npm run tts-pack\` from scenes.yaml.

## Settings
- **Model:** ${g.model ?? "gemini-3.8-flash-tts"}
- **Voice:** ${g.voice ?? "(not chosen yet — set gemini.voice in channel/voice.yaml)"}
- **Language:** English
- **Chunks:** ${chunks.length} (about ${maxWords} words max each, split at scene boundaries)

## How to record
1. Open the Gemini speech generation page in Google AI Studio and pick the model and voice above.
2. Paste the **Style instructions** below into the style / instructions field (not into the text).
3. For each chunk: paste the chunk text, generate, listen once, download the WAV and save it with the file name shown, inside \`${rel(path.join(dir, "audio"))}/\`.
4. Check the pronunciation list while listening; regenerate any chunk that mispronounces a term.
5. Then run \`npm run transcribe -- ${v.name.slice(0, 3)}\` and \`npm run build -- ${v.name.slice(0, 3)}\`.

If a chunk is too long for the tool, split it at a paragraph break and save the parts as e.g. narration-02a.wav and narration-02b.wav (files are joined in name order).

## Style instructions
\`\`\`
${style}
\`\`\`
`;
if (Object.keys(pronounce).length) {
  md += `\n## Pronunciation\n| Term | Say it like |\n|---|---|\n` + Object.entries(pronounce).map(([k, val]) => `| ${k} | ${val} |`).join("\n") + "\n";
}
chunks.forEach((c, i) => {
  const file = `narration-${String(i + 1).padStart(2, "0")}.wav`;
  md += `\n## Chunk ${i + 1} → save as \`audio/${file}\`\nScenes ${c.scenes[0]}–${c.scenes.at(-1)} · ${c.words} words · about ${mmss((c.words / wpm) * 60)}\n\n\`\`\`text\n${c.text.join("\n\n")}\n\`\`\`\n`;
});
fs.writeFileSync(path.join(dir, "tts.md"), md);
fs.mkdirSync(path.join(dir, "audio"), { recursive: true });
ok(`Wrote ${rel(path.join(dir, "script.md"))} and ${rel(path.join(dir, "tts.md"))} (${chunks.length} chunk(s), ${total} words, ~${mmss(t)})`);
saveAndPush(`${v.name.slice(0, 3)}: script and voice package`);
info("Record the chunks in Gemini, save them in audio/, then: npm run transcribe -- <id>");
